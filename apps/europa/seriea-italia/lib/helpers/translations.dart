String formatRound(String? round, [BuildContext? context]) {
  if (round == null || round.trim().isEmpty) return '';
  final trimmed = round.trim();

  final roundWord = context != null ? 'round_label'.tr(context) : 'Rodada';

  final regMatch = RegExp(r'Regular Season\s*-\s*(\d+)', caseSensitive: false).firstMatch(trimmed);
  if (regMatch != null) {
    return '$roundWord ${regMatch.group(1)}';
  }

  final roundMatch = RegExp(r'(Matchday|Round)\s*-\s*(\d+)|(Matchday|Round)\s*(\d+)', caseSensitive: false).firstMatch(trimmed);
  if (roundMatch != null) {
    final num = roundMatch.group(2) ?? roundMatch.group(4);
    return '$roundWord $num';
  }

  final lower = trimmed.toLowerCase();
  if (lower.contains('group stage')) return context != null ? 'group_stage'.tr(context) : 'Fase de Grupos';
  if (lower.contains('quarter-final') || lower.contains('quarter final')) return context != null ? 'quarter_finals'.tr(context) : 'Quartas de Final';
  if (lower.contains('semi-final') || lower.contains('semi final')) return context != null ? 'semi_finals'.tr(context) : 'Semifinais';
  if (lower == 'final') return context != null ? 'final_stage'.tr(context) : 'Final';
  if (lower.contains('play-off') || lower.contains('playoff')) return context != null ? 'playoffs'.tr(context) : 'Play-offs';

  return trimmed;
}
