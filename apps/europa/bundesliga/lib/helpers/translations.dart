String formatRound(String? round) {
  if (round == null || round.trim().isEmpty) return '';
  final trimmed = round.trim();

  final regMatch = RegExp(r'Regular Season\s*-\s*(\d+)', caseSensitive: false).firstMatch(trimmed);
  if (regMatch != null) {
    return 'Rodada ${regMatch.group(1)}';
  }

  final roundMatch = RegExp(r'(Matchday|Round)\s*-\s*(\d+)|(Matchday|Round)\s*(\d+)', caseSensitive: false).firstMatch(trimmed);
  if (roundMatch != null) {
    final num = roundMatch.group(2) ?? roundMatch.group(4);
    return 'Rodada $num';
  }

  final lower = trimmed.toLowerCase();
  if (lower.contains('group stage')) return 'Fase de Grupos';
  if (lower.contains('quarter-final') || lower.contains('quarter final')) return 'Quartas de Final';
  if (lower.contains('semi-final') || lower.contains('semi final')) return 'Semifinais';
  if (lower == 'final') return 'Final';
  if (lower.contains('play-off') || lower.contains('playoff')) return 'Play-offs';

  return trimmed;
}
